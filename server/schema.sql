CREATE TABLE IF NOT EXISTS job_applications (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  role_id VARCHAR(160) NOT NULL,
  name VARCHAR(190) NOT NULL,
  phone VARCHAR(60) NOT NULL,
  email VARCHAR(190) NOT NULL,
  desired_position VARCHAR(190) NOT NULL,
  message TEXT NULL,
  cv_filename VARCHAR(255) NULL,
  cv_path VARCHAR(255) NULL,
  cv_mime VARCHAR(120) NULL,
  cv_size_bytes BIGINT UNSIGNED NULL,
  status ENUM('NEW', 'REVIEWED', 'ARCHIVED') NOT NULL DEFAULT 'NEW',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
